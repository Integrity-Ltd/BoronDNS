export OXIDEDNS_PHYSICAL_NSD_PORT="${OXIDEDNS_PHYSICAL_NSD_PORT:-5302}"
export OXIDEDNS_PHYSICAL_NSD_XDP_PORT="${OXIDEDNS_PHYSICAL_NSD_XDP_PORT:-53}"
export OXIDEDNS_PHYSICAL_NSD_SERVER_COUNT="${OXIDEDNS_PHYSICAL_NSD_SERVER_COUNT:-48}"

